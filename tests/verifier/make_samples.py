"""
Build docs/verify/samples.js from a REAL arena run, plus two deliberately
tampered copies, for the 'Load sample' buttons on the verifier page.

    bash scripts/demo.sh            # writes /tmp/chakravyuh_export.json + /tmp/chakravyuh_report.json
    PYTHONPATH=. python3 tests/verifier/make_samples.py /tmp/chakravyuh_export.json /tmp/chakravyuh_report.json

Raw JSON text is embedded verbatim (as a JS string) so number text such as 50.0
survives exactly as the arena wrote it.
"""
import datetime
import json
import os
import sys


def dump(obj):
    # same wire format the broker uses (Starlette JSONResponse)
    return json.dumps(obj, ensure_ascii=False, separators=(",", ":"))


def main(export_path, report_path):
    export_raw = open(export_path).read()
    report_raw = open(report_path).read()

    tampered_export = json.loads(export_raw)
    flipped = None
    for r in tampered_export["records"]:
        if r["action"] == "attack_routed" and r["detail"].get("blocked") is True:
            r["detail"]["blocked"] = False          # quietly turn a block into a pass
            flipped = r["seq"]
            break
    tampered_report = json.loads(report_raw)
    tampered_report["report"]["canary_leaks"] = 5   # claim leaks that never happened

    samples = {
        "meta": {
            "generated": datetime.date.today().isoformat(),
            "note": "Genuine samples are unmodified output of scripts/demo.sh. "
                    f"Tampered log: record #{flipped} 'blocked' flipped true->false. "
                    "Tampered report: canary_leaks changed 0->5.",
            "flipped_seq": flipped,
        },
        "export_genuine": export_raw,
        "report_genuine": report_raw,
        "export_tampered": dump(tampered_export),
        "report_tampered": dump(tampered_report),
    }
    out = os.path.join(os.path.dirname(__file__), "..", "..", "docs", "verify", "samples.js")
    with open(out, "w") as fh:
        fh.write("// Generated by tests/verifier/make_samples.py from a real Chakravyuh run.\n")
        fh.write("// Raw JSON text is kept verbatim so number formatting is preserved.\n")
        fh.write("window.CHAK_SAMPLES = " + json.dumps(samples, indent=1) + ";\n")
    print("wrote", os.path.normpath(out), "| flipped record:", flipped)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
